"""Coverage report for a collected dataset, and verification of the RAM address map (ROADMAP CP2-A).

    python scripts/coverage_report.py data/debug             # markdown report, histograms, montages
    python scripts/coverage_report.py --verify-ram           # docs/figures/cp2_ram_verify.png

Outputs go to --out-dir (default docs/figures) as cp2_coverage_* and cp2_ram_verify.png.
"""

import argparse
import json
from pathlib import Path

import imageio.v3 as iio
import matplotlib

matplotlib.use("Agg")  # headless: only saves files
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from wm.data import coverage, ram  # noqa: E402
from wm.data.reader import ShardReader, list_shards  # noqa: E402
from wm.data.schema import END_TERMINATED, SOURCE_AGENT, SOURCE_HUMAN, SOURCE_RANDOM  # noqa: E402

SOURCE_NAMES = {SOURCE_AGENT: "agent", SOURCE_RANDOM: "random", SOURCE_HUMAN: "human"}
BAR = "#3b6ea8"  # one hue: every panel shows a single series
MONTAGE_N, MONTAGE_SCALE = 16, 3


def _style(ax: plt.Axes, title: str, xlabel: str, ylabel: str) -> None:
    ax.set_title(title, fontsize=10)
    ax.set_xlabel(xlabel, fontsize=8)
    ax.set_ylabel(ylabel, fontsize=8)
    ax.tick_params(labelsize=7)
    ax.grid(axis="y", color="#e3e3e3", linewidth=0.6)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)


def save_histograms(cov: coverage.Coverage, path: Path) -> None:
    """Score, episode length, invaders left, lives, and source histograms."""
    e, f = cov.episodes, cov.frames
    fig, axes = plt.subplots(1, 5, figsize=(17, 3.2))
    axes[0].hist(e["return_"], bins=30, color=BAR, edgecolor="white", linewidth=0.5)
    _style(axes[0], "Score per episode", "score", "episodes")
    axes[1].hist(e["length"] - 1, bins=30, color=BAR, edgecolor="white", linewidth=0.5)
    _style(axes[1], "Episode length", "agent steps", "episodes")
    axes[2].hist(f["invaders"], bins=np.arange(ram.WAVE_SIZE + 2) - 0.5, color=BAR, edgecolor="white", linewidth=0.5)
    _style(axes[2], "Invaders left", "invaders (RAM)", "frames")
    axes[3].hist(f["lives"], bins=np.arange(5) - 0.5, color=BAR, edgecolor="white", linewidth=0.5)
    _style(axes[3], "Lives", "lives", "frames")
    sources = sorted(set(e["source"].tolist()))
    steps = [int((e["length"][e["source"] == s] - 1).sum()) for s in sources]
    axes[4].bar([SOURCE_NAMES.get(s, str(s)) for s in sources], steps, color=BAR, width=0.6)
    _style(axes[4], "Source", "", "agent steps")
    fig.tight_layout()
    fig.savefig(path, dpi=110)
    plt.close(fig)


def buckets(cov: coverage.Coverage) -> dict[str, np.ndarray]:
    """Frame masks whose montages let a person check each heuristic."""
    f = cov.frames
    return {"ufo": f["ufo"], "few_invaders": f["invaders"] <= 6, "shields_low": f["shield_ratio"] <= 0.5,
            "life_lost": f["life_lost"], "wave_start": f["wave_start"], "game_over": f["terminal"]}


def save_montage(dataset_dir: Path, cov: coverage.Coverage, mask: np.ndarray, path: Path,
                 rng: np.random.Generator) -> int:
    """Save up to 16 random frames of a bucket as a 4x4 grid (3x nearest, no aspect change)."""
    idx = np.flatnonzero(mask)
    if len(idx) == 0:
        return 0
    idx = np.sort(rng.choice(idx, min(MONTAGE_N, len(idx)), replace=False))
    shards, rows = cov.frames["shard"][idx], cov.frames["row"][idx]
    paths = list_shards(dataset_dir)
    frames = np.concatenate([ShardReader(paths[s]).read("frames", rows[shards == s]) for s in np.unique(shards)])
    frames = frames.repeat(MONTAGE_SCALE, axis=1).repeat(MONTAGE_SCALE, axis=2)
    tiles = list(frames) + [np.full_like(frames[0], 255)] * (MONTAGE_N - len(frames))
    pad = lambda t: np.pad(t, ((2, 2), (2, 2), (0, 0)), constant_values=255)  # noqa: E731
    grid = np.concatenate([np.concatenate([pad(t) for t in tiles[r:r + 4]], axis=1) for r in range(0, MONTAGE_N, 4)])
    iio.imwrite(path, grid)
    return len(frames)


def write_report(dataset_dir: Path, cov: coverage.Coverage, out_dir: Path, montages: dict[str, int]) -> Path:
    """Write cp2_coverage_report.md and return its path."""
    e, f = cov.episodes, cov.frames
    values = coverage.target_values(cov)
    lines = [f"# CP2 coverage report: `{dataset_dir}`", "",
             f"Generated by `python scripts/coverage_report.py {dataset_dir}`.", "",
             f"{len(list_shards(dataset_dir))} shards, {len(f['lives']):,} rows, {len(e['length']):,} episodes, "
             f"{int((e['length'] - 1).sum()):,} agent steps.", "",
             "## Targets", "", "| Target | Minimum | Measured | Met |", "|---|---|---|---|"]
    for name, (minimum, is_fraction) in coverage.TARGETS.items():
        v = values[name]
        shown = (f"{100 * minimum:g}%", f"{100 * v:.2f}%") if is_fraction else (f"{minimum:g}", f"{v:,}")
        lines.append(f"| {name} | {shown[0]} | {shown[1]} | {'yes' if v >= minimum else '**no**'} |")
    lines += ["", "## By source", "", "| Source | Episodes | Agent steps | Mean score | Game overs |",
              "|---|---|---|---|---|"]
    for s in sorted(set(e["source"].tolist())):
        m = e["source"] == s
        lines.append(f"| {SOURCE_NAMES.get(s, s)} | {int(m.sum()):,} | {int((e['length'][m] - 1).sum()):,} | "
                     f"{float(e['return_'][m].mean()):.1f} | {int((e['end_reason'][m] == END_TERMINATED).sum())} |")
    agree = float(np.mean(f["ufo"] == f["ufo_ram"])) if len(f["ufo"]) else 0.0
    lines += ["", "## Events", "",
              f"- Life losses: {cov.events['life_losses']:,}",
              f"- Game overs: {cov.events['game_overs']:,}",
              f"- Wave transitions (invaders left jumps back up): {cov.events['wave_transitions']:,}",
              f"- Score per episode: mean {float(e['return_'].mean()):.1f}, max {float(e['return_'].max()):.0f}",
              "", "## Heuristic checks", "",
              f"- UFO pixel heuristic (magenta in the top band) agrees with RAM[{ram.UFO_STATE}] >= "
              f"{ram.UFO_ACTIVE_MIN} on {100 * agree:.2f}% of frames.",
              "- Shield erosion is shield-colour pixels in the shield band, relative to the episode's first frame.",
              "", "## Figures", "", "![histograms](cp2_coverage_hist.png)", "",
              f"Montages: up to {MONTAGE_N} random frames per bucket, {MONTAGE_SCALE}x nearest, not aspect-corrected.", ""]
    for name, n in montages.items():
        lines.append(f"- `{name}` ({n} frames): ![{name}](cp2_coverage_montage_{name}.png)" if n
                     else f"- `{name}`: no frames in this bucket")
    path = out_dir / "cp2_coverage_report.md"
    path.write_text("\n".join(lines) + "\n")
    return path


def coverage_report(dataset_dir: Path, out_dir: Path, seed: int) -> None:
    cov = coverage.dataset_coverage(dataset_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    save_histograms(cov, out_dir / "cp2_coverage_hist.png")
    rng = np.random.default_rng(seed)
    montages = {name: save_montage(dataset_dir, cov, mask, out_dir / f"cp2_coverage_montage_{name}.png", rng)
                for name, mask in buckets(cov).items()}
    report = write_report(dataset_dir, cov, out_dir, montages)
    values = coverage.target_values(cov)
    print(json.dumps({"events": cov.events, "targets": values}, indent=2))
    print(f"wrote {report}")


# --- RAM verification ----------------------------------------------------------------------


def _first(mask: np.ndarray, axis: int) -> float:
    hits = np.flatnonzero(mask.any(axis=axis))
    return float(hits[0]) if len(hits) else np.nan


def _alien_blobs(mask: np.ndarray) -> int:
    import cv2

    return cv2.connectedComponents(mask.astype(np.uint8), connectivity=8)[0] - 1


def ram_rollout(seeds: list[int], epsilon: float) -> dict[str, np.ndarray]:
    """Per agent step: RAM and frame/reward/info measures from a seeded epsilon-mix agent."""
    from wm.agents.policies import EpsilonMixPolicy
    from wm.agents.pretrained import ZooAgentPolicy
    from wm.env import make_env

    def colour(obs: np.ndarray, rgb: tuple[int, int, int]) -> np.ndarray:
        return (obs == np.array(rgb, np.uint8)).all(-1)

    policy = EpsilonMixPolicy(ZooAgentPolicy(), epsilon)
    rec = {k: [] for k in ("ram", "lives", "reward", "episode", "game_over", "player_x", "aliens_x",
                           "aliens_y", "alien_blobs", "ufo_pixels")}
    for seed in seeds:
        env = make_env(seed)
        obs, info = env.reset()
        policy.reset(seed, obs)
        reward, done, terminated = 0.0, False, False
        while True:
            player = colour(obs, (50, 132, 50))
            player[:185], player[195:] = False, False  # the score digits share the player's colour
            aliens = colour(obs, (134, 134, 29))
            aliens[:31] = False
            ufo = colour(obs, coverage.UFO_RGB)
            ufo[coverage.UFO_RAW_ROWS[1]:] = False
            for k, v in (("ram", env.unwrapped.ale.getRAM().copy()), ("lives", info["lives"]), ("reward", reward),
                         ("episode", seed), ("game_over", terminated), ("player_x", _first(player, 0)),
                         ("aliens_x", _first(aliens, 0)), ("aliens_y", _first(aliens, 1)),
                         ("alien_blobs", _alien_blobs(aliens)), ("ufo_pixels", bool(ufo.any()))):
                rec[k].append(v)
            if done:
                break
            obs, reward, terminated, truncated, info = env.step(policy.act(obs))
            done = terminated or truncated
        env.close()
    return {k: np.array(v) for k, v in rec.items()}


def verify_ram(out_dir: Path, seeds: list[int], epsilon: float) -> None:
    """Plot each RAM address against its frame/reward measure and print the agreement."""
    d = ram_rollout(seeds, epsilon)
    r = d["ram"].astype(np.int64)
    same = d["episode"][1:] == d["episode"][:-1]
    cum = np.zeros(len(r))
    for i in range(1, len(r)):
        cum[i] = d["reward"][i] + (cum[i - 1] if same[i - 1] else 0)
    kill = (d["reward"][1:] > 0) & (d["reward"][1:] <= 30) & same
    drop = (np.diff(r[:, ram.INVADERS_LEFT]) == -1) & same
    alive = ~d["game_over"]

    def corr(a: np.ndarray, b: np.ndarray) -> float:
        ok = ~np.isnan(b)
        return float(np.corrcoef(a[ok], b[ok])[0, 1])

    panels = [  # (title, x, y, xlabel, ylabel, verdict)
        (f"lives = RAM[{ram.LIVES}]", d["lives"][alive], r[alive, ram.LIVES], "info['lives']", "RAM",
         f"equal on {100 * np.mean(r[alive, ram.LIVES] == d['lives'][alive]):.2f}% (not game-over frames)"),
        (f"invaders left = RAM[{ram.INVADERS_LEFT}]", d["alien_blobs"], r[:, ram.INVADERS_LEFT],
         "alien-colour blobs on screen", "RAM",
         f"-1 on every alien-kill reward: {100 * np.mean(drop[same] == kill[same]):.2f}% of steps"),
        (f"score = BCD RAM[{ram.SCORE_HI}],[{ram.SCORE_LO}]", cum, ram.score(r), "cumulative reward", "RAM",
         f"equal on {100 * np.mean(ram.score(r) == cum):.2f}%"),
        (f"player x = RAM[{ram.PLAYER_X}]", d["player_x"], r[:, ram.PLAYER_X], "player sprite left column", "RAM",
         f"r = {corr(r[:, ram.PLAYER_X], d['player_x']):.3f}"),
        (f"aliens x = RAM[{ram.ALIENS_X}]", d["aliens_x"], r[:, ram.ALIENS_X], "alien block left column", "RAM",
         f"r = {corr(r[:, ram.ALIENS_X], d['aliens_x']):.3f}"),
        (f"aliens y = RAM[{ram.ALIENS_Y}]", d["aliens_y"], r[:, ram.ALIENS_Y], "alien block top row", "RAM",
         f"r = {corr(r[:, ram.ALIENS_Y], d['aliens_y']):.3f}"),
        (f"UFO = RAM[{ram.UFO_STATE}] >= {ram.UFO_ACTIVE_MIN}", d["ufo_pixels"].astype(float), r[:, ram.UFO_STATE],
         "UFO pixels on screen (0/1)", "RAM",
         f"agree on {100 * np.mean(ram.ufo_active(r) == d['ufo_pixels']):.2f}%"),
        ("rejected: AtariARI score = RAM[23]", cum, r[:, 23], "cumulative reward", "RAM",
         f"r = {corr(r[:, 23].astype(float), cum):.3f}"),
        ("rejected: AtariARI enemies_y = RAM[24]", d["aliens_y"], r[:, 24], "alien block top row", "RAM",
         f"r = {corr(r[:, 24].astype(float), d['aliens_y']):.3f}"),
    ]
    fig, axes = plt.subplots(3, 3, figsize=(13, 11))
    for ax, (title, x, y, xl, yl, verdict) in zip(axes.flat, panels):
        ax.scatter(x, y, s=8, color=BAR, alpha=0.35, linewidths=0)
        _style(ax, f"{title}\n{verdict}", xl, yl)
        print(f"{title}: {verdict}")
    fig.suptitle(f"RAM verification: epsilon={epsilon} agent, seeds {seeds}, {len(r)} frames", fontsize=11)
    fig.tight_layout()
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "cp2_ram_verify.png"
    fig.savefig(path, dpi=100)
    plt.close(fig)
    print(f"wrote {path}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("dataset_dir", type=Path, nargs="?", help="dataset to report on")
    parser.add_argument("--out-dir", type=Path, default=Path("docs/figures"))
    parser.add_argument("--seed", type=int, default=0, help="montage sampling seed")
    parser.add_argument("--verify-ram", action="store_true", help="verify the RAM map with agent rollouts")
    parser.add_argument("--verify-seeds", type=int, nargs="+", default=[0, 1, 2])
    parser.add_argument("--verify-epsilon", type=float, default=0.1)
    args = parser.parse_args()
    if args.verify_ram:
        verify_ram(args.out_dir, args.verify_seeds, args.verify_epsilon)
    if args.dataset_dir is not None:
        coverage_report(args.dataset_dir, args.out_dir, args.seed)
    elif not args.verify_ram:
        parser.error("give a dataset_dir, --verify-ram, or both")


if __name__ == "__main__":
    main()
